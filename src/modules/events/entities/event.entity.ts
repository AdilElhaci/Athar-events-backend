import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { Package } from '../../packages/entities/package.entity';
import { User } from '../../users/entities/user.entity';

export enum EventStatus {
  DRAFT = 'DRAFT',
  ACTIVE = 'ACTIVE',
  CLOSED = 'CLOSED',
  CANCELLED = 'CANCELLED',
}

export enum EventPaymentStatus {
  UNPAID = 'UNPAID',
  PENDING = 'PENDING',
  PAID = 'PAID',
  REFUNDED = 'REFUNDED',
}

export enum EventListStatus {
  AWAITING_LIST = 'AWAITING_LIST',
  IN_PROGRESS = 'IN_PROGRESS',
  READY = 'READY',
}

export enum EventApprovalStatus {
  NOT_REQUESTED = 'NOT_REQUESTED',
  AWAITING_OWNER = 'AWAITING_OWNER',
  APPROVED = 'APPROVED',
}

export enum EventCampaignStatus {
  NOT_SCHEDULED = 'NOT_SCHEDULED',
  SCHEDULED = 'SCHEDULED',
  SENDING = 'SENDING',
  PAUSED = 'PAUSED',
  SENT = 'SENT',
  CANCELLED = 'CANCELLED',
}

/**
 * One purchase of a package for one occasion. The package terms are copied here at creation,
 * so catalogue edits never reach an existing event (AC-04-2).
 */
@Entity({ name: 'events' })
@Index('IDX_events_owner_id', ['ownerId'])
@Check(
  'CHK_events_admission_window',
  '"admission_opens_at" < "admission_closes_at"',
)
@Check(
  'CHK_events_requested_send_at',
  '"requested_send_at" IS NULL OR "requested_send_at" < "starts_at"',
)
@Check('CHK_events_send_at', '"send_at" IS NULL OR "send_at" < "starts_at"')
export class Event {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  @Column({ name: 'owner_id', type: 'uuid' })
  ownerId!: string;

  @ManyToOne(() => User, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'owner_id', foreignKeyConstraintName: 'FK_events_owner' })
  owner?: User;

  /** Human reference quoted to the operations team; generated by the database from a sequence. */
  @Column({
    name: 'reference_code',
    type: 'varchar',
    length: 16,
    unique: true,
    default: () =>
      `'AE-' || lpad(nextval('events_reference_seq')::text, 6, '0')`,
  })
  referenceCode!: string;

  @Column({ type: 'varchar', length: 120 })
  name!: string;

  @Column({ name: 'starts_at', type: 'timestamptz' })
  startsAt!: Date;

  @Column({ type: 'varchar', length: 40, default: 'Asia/Riyadh' })
  timezone!: string;

  @Column({ name: 'venue_name', type: 'varchar', length: 160 })
  venueName!: string;

  @Column({
    name: 'venue_map_url',
    type: 'varchar',
    length: 500,
    nullable: true,
  })
  venueMapUrl!: string | null;

  /** The owner's wish; an admin confirms the real send time in `sendAt`. */
  @Column({ name: 'requested_send_at', type: 'timestamptz', nullable: true })
  requestedSendAt!: Date | null;

  /** Reference only: the terms below are what the event actually bought. */
  @Column({ name: 'package_id', type: 'uuid', nullable: true })
  packageId!: string | null;

  @ManyToOne(() => Package, { onDelete: 'SET NULL' })
  @JoinColumn({
    name: 'package_id',
    foreignKeyConstraintName: 'FK_events_package',
  })
  package?: Package | null;

  @Column({ name: 'package_name', type: 'varchar', length: 80 })
  packageName!: string;

  @Column({ name: 'invitation_allowance', type: 'int' })
  invitationAllowance!: number;

  @Column({ name: 'extra_margin', type: 'int' })
  extraMargin!: number;

  @Column({ name: 'price_halalas', type: 'int' })
  priceHalalas!: number;

  @Column({ type: 'varchar', length: 3 })
  currency!: string;

  @Column({
    type: 'enum',
    enum: EventStatus,
    enumName: 'event_status',
    default: EventStatus.DRAFT,
  })
  status!: EventStatus;

  @Column({
    name: 'payment_status',
    type: 'enum',
    enum: EventPaymentStatus,
    enumName: 'event_payment_status',
    default: EventPaymentStatus.UNPAID,
  })
  paymentStatus!: EventPaymentStatus;

  @Column({
    name: 'list_status',
    type: 'enum',
    enum: EventListStatus,
    enumName: 'event_list_status',
    default: EventListStatus.AWAITING_LIST,
  })
  listStatus!: EventListStatus;

  @Column({
    name: 'approval_status',
    type: 'enum',
    enum: EventApprovalStatus,
    enumName: 'event_approval_status',
    default: EventApprovalStatus.NOT_REQUESTED,
  })
  approvalStatus!: EventApprovalStatus;

  @Column({
    name: 'campaign_status',
    type: 'enum',
    enum: EventCampaignStatus,
    enumName: 'event_campaign_status',
    default: EventCampaignStatus.NOT_SCHEDULED,
  })
  campaignStatus!: EventCampaignStatus;

  @Column({ name: 'send_at', type: 'timestamptz', nullable: true })
  sendAt!: Date | null;

  /** Bumped on every schedule change; jobs carry it and do nothing on a mismatch. */
  @Column({ name: 'schedule_version', type: 'int', default: 0 })
  scheduleVersion!: number;

  @Column({ name: 'admission_opens_at', type: 'timestamptz' })
  admissionOpensAt!: Date;

  @Column({ name: 'admission_closes_at', type: 'timestamptz' })
  admissionClosesAt!: Date;

  @Column({ name: 'paid_at', type: 'timestamptz', nullable: true })
  paidAt!: Date | null;

  @Column({ name: 'cancelled_at', type: 'timestamptz', nullable: true })
  cancelledAt!: Date | null;

  @Column({ name: 'closed_at', type: 'timestamptz', nullable: true })
  closedAt!: Date | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;
}
